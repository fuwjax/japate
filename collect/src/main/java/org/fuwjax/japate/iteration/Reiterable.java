package org.fuwjax.japate.iteration;

import java.util.Iterator;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.function.BiFunction;
import java.util.function.Function;
import java.util.function.Predicate;

import org.fuwjax.japate.iteration.iterator.ArrayIterator;
import org.fuwjax.japate.iteration.iterator.EmptyIterator;
import org.fuwjax.japate.iteration.iterator.FilterIterator;
import org.fuwjax.japate.iteration.iterator.LoopIterator;
import org.fuwjax.japate.iteration.iterator.MapIterator;
import org.fuwjax.japate.iteration.iterator.MergeIterator;
import org.fuwjax.japate.iteration.iterator.UntilIterator;

/**
 * Reiterable adds map/reduce functionality as well as other convenience methods to the standard Iterable interface.
 * 
 * The most straightforward way to arrive at a Reiterable is to either have a custom class that implements Iterable to instead
 * implement Reiterable, or to use the Reiterable.re() static constructor to convert any iterable into a reiterable.
 * 
 * It should be noted that nearly every operation in this list is functional, i.e. no cloning or copying of the underlying storage
 * is performed. Changes to any underlying storage will be exposed, with potentially unintended or unwanted side effects. No checks
 * are made for current modifications, or modifications at all. This is not intended to be a universal replacement for Iterable.
 * Reiterable will be most useful in cases where the underlying data structure is effectively immutable or unmodifiable. If it would
 * be valuable in other contexts, it is recommended to copy or clone the underlying data first, or provide some other mechanism to
 * limit mutability.
 * 
 * @param <T>
 */
public interface Reiterable<T> extends Iterable<T> {
    /**
     * Standard empty iterable.
     * @param <T> the iteration type
     * @return a reiterable whose hasNext() will always return false, and next() will always throw a NoSuchElementException
     */
    static <T> Reiterable<T> empty() {
        return EmptyIterator::new;
    }

    /**
     * Wrapper conversion from Iterable to Reiterable. This is the standard way to use Reiterable with third party iterators.
     * @param <T> the iteration type
     * @param iter the stock iterable
     * @return the reiterable
     */
    static <T> Reiterable<T> re(Iterable<T> iter) {
        if(iter == null) {
            return empty();
        }
        if(iter instanceof Reiterable<T> rei) {
            return rei;
        }
        return iter::iterator;
    }

    /**
     * Wrapper for arrays/varargs. This is borderline dirty, as it will construct a generic typed array for the varargs. As
     * Reiterable is immutable, this should have no real impact.
     * @param <T> the iteration type
     * @param array the iteration values
     * @return the reiterable
     */
    @SafeVarargs 
    static <T> Reiterable<T> of(T... array) {
        return () -> new ArrayIterator<>(array);
    }

    /**
     * Returns a reiterable that produces the integers from start to stop, incrementing by 1 with each call to next.
     * @param start the first result to return from the iterator
     * @param stop the first result to not return from the iterator
     * @return the reiterable
     */
    static Reiterable<Integer> range(int start, int stop) {
        return range(start, stop, 1);
    }

    /**
     * Returns a reiterable that produces the integers from start to stop, incrementing by step with each call to next.
     * @param start the first result to return from the iterator
     * @param stop the first result to not return from the iterator
     * @param step the increment between each returned result
     * @return the reiterable
     */
    static Reiterable<Integer> range(int start, int stop, int step) {
        assert step != 0 || start == stop;
        return loop(start, i -> i + step, i -> step > 0 ? i >= stop : i <= stop);
    }

    /**
     * Returns a reiterable that is generated by the walker function initialized with the start value until the stop predicate returns true.
     * Note that the reiterable is effectively empty if the start value tests true with the stop predicate.
     * @param <T> the iteration type
     * @param start the initial value
     * @param walker the generator function
     * @param stop the termination condition
     * @return the reiterable
     */
    static <T> Reiterable<T> loop(T start, Function<? super T, ? extends T> walker, Predicate<? super T> stop) {
        return () -> new LoopIterator<T>(start, walker, stop);
    }

    /**
     * Returns a Reiterable that iterates over values of the iterables in inception in order, effectively merging those iterables into a single iteration.
     * @param <T> the iteration type
     * @param inception the iterable of iterables to flatten
     * @return the reiterable representing the flattened iteration
     */
    static <T> Reiterable<T> flatten(Iterable<? extends Iterable<? extends T>> inception) {
        return () -> new MergeIterator<T>(re(inception).map(Iterable::iterator).iterator());
    }

    /**
     * Aborts the iteration once a sentinel value is detected by the stop test.
     * @param stop the condition to abort iteration.
     * @return an iterator that iterates until stop is true
     */
    default Reiterable<T> until(Predicate<? super T> stop) {
        return () -> new UntilIterator<>(iterator(), stop);
    }

    /**
     * Appends follower to the end of this iterable, such that when this iterable would return false from hasNext(), it instead continues with the elements in follower.
     * @param follower the iterable to append
     * @return the Reiterable representing the merged iterables
     */
    default Reiterable<T> append(Iterable<? extends T> follower) {
        return flatten(List.of(this, follower));
    }

    /**
     * Filters iteration values according to the test predicate. Note the reiterable will appear empty if the test predicate returns true for all iterated values.
     * @param test the condition for returning from next()
     * @return the reiterable representing the true values in the underlying iterable, according to the test condition
     */
    default Reiterable<T> filter(Predicate<? super T> test) {
        return () -> new FilterIterator<>(iterator(), test);
    }

    /**
     * Maps each value returned by this iterable to the value returned by the func operation. Note that generated values are not buffered. It is recommended to 
     * preserve the values in a new collection if they are expensive or intended to be frequently reused.
     * @param <R> the result of the mapping function and iteration type of the resulting reiterable
     * @param func the mapping function
     * @return the reiterable
     */
    default <R> Reiterable<R> map(Function<? super T, ? extends R> func) {
        return () -> new MapIterator<>(iterator(), func);
    }

    /**
     * Accumulates the result of the aggregator into a value object initialized with init.
     * @param <R> the accumulator object
     * @param init the initial value of the accumulator
     * @param aggregator the aggregation operation
     * @return the accumulated result
     */
    default <R> R reduce(R init, BiFunction<? super R, ? super T, ? extends R> aggregator) {
        R curr = init;
        for(T value: this) {
            curr = aggregator.apply(curr, value);
        }
        return curr;
    }

    /**
     * Maps the elements of this iterable to their typed equivalent. Note that no conversion takes place, only casting via Class.cast().
     * @param <R> the resulting iteration type
     * @param type the iteration type
     * @return the typed reiterable
     */
    default <R> Reiterable<R> as(Class<R> type) {
        return map(type::cast);
    }

    /**
     * Returns true if the iterator will always return false for hasNext().
     * @return true if iterator().hasNext() would return false, false otherwise.
     */
    default boolean isEmpty() {
        return !iterator().hasNext();
    }

    /**
     * Returns an Optional representing the first non-null element from this iterable, or Optional.empty() if this iterable is empty.
     * @return the first element in this iterable, or empty if none exists
     */
    default Optional<T> first() {
        Iterator<T> iter = filter(o -> o != null).iterator();
        return iter.hasNext() ? Optional.of(iter.next()) : Optional.empty();
    }

    default Optional<T> select(int index) {
        int count = 0;
        for(T t: filter(o -> o != null)) {
            if(count++ == index) {
                return Optional.ofNullable(t);
            }
        }
        return Optional.empty();
    }

    /**
     * Joins the toString representations of the elements in this iterable as a single string.
     * @return the joined string
     */
    default String join() {
        return reduce(new StringBuilder(),StringBuilder::append).toString();
    }

    /**
     * Joins the toString representations of the elements in this iterable as a single string separated by the delim value.
     * @return the joined string
     */
    default String join(String delim) {
        StringBuilder s = new StringBuilder();
        boolean first = true;
        for(T value: this) {
            s.append(first ? "" : delim).append(value);
            first = false;
        }
        return s.toString();
    }

    /**
     * Returns the number of elements enumerated by this iterable.
     * @return the count of elements
     */
    default int count() {
        return reduce(0, (c, e) -> c + 1);
    }

    /**
     * Returns true if any element in this iterable is true according to the test condition.
     * @param test the test condition
     * @return true if any elements test true, false if all test false
     */
    default boolean any(Predicate<? super T> test) {
        return !filter(test).isEmpty();
    }

    /**
     * Returns true if any element in this iterable test true for simple equality to e.
     * @param e the compared value
     * @return true if any element equals e, false otherwise
     */
    default boolean contains(Object e) {
        return any(x -> Objects.equals(x, e));
    }

    /**
     * Returns an unmodifiable List representation of this iterable. Note that while the returned List
     * is unmodifiable, that in no way limits the storage backing this iterable.
     * @return the List view of this iterable
     */
    default ListView<T> asList() {
        return ListView.over(this);
    }

    /**
     * Returns an unmodifiable Set representation of this iterable. Note that while the returned Set
     * is unmodifiable, that in no way limits the storage backing this iterable. Note also, no attempt
     * is made to force the values of this iterable to be unique. Set semantics must be enforced by the
     * caller of this method.
     * @return the Set view of this iterable
     */
    default SetView<T> asSet() {
        return SetView.over(this);
    }

    /**
     * Returns an unmodifiable Map representation of this iterable, indexed by the results returned by the key
     * extraction function. Note that while the returned Map
     * is unmodifiable, that in no way limits the storage backing this iterable. Note also, no attempt
     * is made to force the values of this iterable to be unique. Map semantics must be enforced by the
     * caller of this method.
     * @param <K> the key type
     * @param key the key extraction
     * @return the Map view of this iterable
     */
    default <K> MapView<K, T> asMap(Function<? super T, K> key) {
        return MapView.over(this, key);
    }

    /**
     * Returns an unmodifiable Map representation of this iterable, indexed by the results returned by the key
     * extraction function and mapping to the result returned by the value extraction function. Note that while the returned Map
     * is unmodifiable, that in no way limits the storage backing this iterable. Note also, no attempt
     * is made to force the values of this iterable to be unique. Map semantics must be enforced by the
     * caller of this method.
     * @param <K> the key type
     * @param key the key extraction
     * @return the Map view of this iterable
     */
    default <K, V> MapView<K, V> asMap(Function<T, K> key, Function<T, V> value) {
        return MapView.over(this, key, value);
    }
}
